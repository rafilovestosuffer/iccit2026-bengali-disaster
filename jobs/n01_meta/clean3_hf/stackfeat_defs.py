def text_feats(t):
    t = "" if t is None else str(t)
    n = max(len(t), 1)
    row = [
        len(t),
        len(t.split()),
        len(BANGLA_RE.findall(t)) / n,
        len(re.findall(r"[a-zA-Z]", t)) / n,
        len(re.findall(r"\d", t)) / n,
        t.count("।") + t.count("."),
        int("?" in t),
        int("!" in t),
        int(any(e in t for e in NON_DIS_EMOJI)),
        int(any(e in t for e in LANDSLIDE_EMOJI)),
        int(any(e in t for e in HUMDAM_EMOJI)),
        int('🔥' in t),
        int('😭' in t or '😞' in t or '😥' in t),
    ]
    for kws in KEYWORDS.values():
        row.append(sum(t.count(k) for k in kws))
    return row  # 21 features total
